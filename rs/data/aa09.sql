CREATE DATABASE IF NOT EXISTS `aa09` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `aa09`;
SET NAMES utf8mb4;

-- ----------------------------
-- 用户表
-- ----------------------------
DROP TABLE IF EXISTS `user`;
CREATE TABLE `user` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `username` VARCHAR(50) UNIQUE NOT NULL,
  `password` VARCHAR(100) NOT NULL,
  `real_name` VARCHAR(50),
  `phone` VARCHAR(20),
  `role` INT NOT NULL COMMENT '0-管理员 1-月嫂 2-营养师 3-护理人员 4-客户',
  `avatar` VARCHAR(255),
  `status` INT DEFAULT 1 COMMENT '0-禁用 1-启用',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ----------------------------
-- 服务项目表
-- ----------------------------
DROP TABLE IF EXISTS `service_item`;
CREATE TABLE `service_item` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `name` VARCHAR(100) NOT NULL,
  `description` TEXT,
  `image` VARCHAR(255),
  `price` DECIMAL(10,2),
  `status` INT DEFAULT 1 COMMENT '0-下架 1-上架',
  `category` VARCHAR(50) COMMENT '服务分类',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ----------------------------
-- 套餐表
-- ----------------------------
DROP TABLE IF EXISTS `package`;
CREATE TABLE `package` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `name` VARCHAR(100) NOT NULL,
  `description` TEXT,
  `price` DECIMAL(10,2),
  `duration` INT COMMENT '服务天数',
  `services` TEXT COMMENT '包含的服务项目描述',
  `status` INT DEFAULT 1 COMMENT '0-下架 1-上架',
  `image` VARCHAR(255),
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ----------------------------
-- 订单表
-- ----------------------------
DROP TABLE IF EXISTS `orders`;
CREATE TABLE `orders` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `order_no` VARCHAR(50) UNIQUE NOT NULL,
  `customer_id` INT NOT NULL,
  `package_id` INT,
  `total_price` DECIMAL(10,2),
  `status` INT DEFAULT 0 COMMENT '0-待审核 1-已确认 2-服务中 3-已完成 4-已取消',
  `expected_date` DATE,
  `start_date` DATE,
  `end_date` DATE,
  `remark` TEXT,
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ----------------------------
-- 产妇信息表（预约时录入）
-- ----------------------------
DROP TABLE IF EXISTS `order_maternal`;
CREATE TABLE `order_maternal` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `order_id` INT NOT NULL,
  `name` VARCHAR(50) COMMENT '产妇姓名',
  `age` INT COMMENT '年龄',
  `phone` VARCHAR(20) COMMENT '联系电话',
  `delivery_type` VARCHAR(20) COMMENT '分娩方式：顺产/剖腹产',
  `delivery_date` DATE COMMENT '分娩日期',
  `health_note` TEXT COMMENT '健康备注（过敏、既往病史等）',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ----------------------------
-- 婴儿信息表（预约时录入，支持多个婴儿）
